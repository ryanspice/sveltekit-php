#!/usr/bin/env bun
import { spawn } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { config as loadEnv } from 'dotenv';
import { assertDeployEnv, assertHostedSmokeEnv, normalizeBase } from './utils/config.mjs';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const devBasePath = normalizeBase(process.env.ALPHA_DEV_BASE_PATH || '/dev/sveltekitphp');
const args = new Set(process.argv.slice(2));

const apply = args.has('--apply');
const smoke = args.has('--smoke') || args.has('--hosted-smoke');
const skipBuild = args.has('--skip-build');
const buildOnly = args.has('--build-only');

loadEnv({ quiet: true });

process.env.SK_BASE_PATH = devBasePath;
process.env.DEPLOY_BASE = devBasePath;
process.env.ADAPTER_MODE = process.env.ADAPTER_MODE || 'php-static';
process.env.DEPLOY_LOCAL = process.env.DEPLOY_LOCAL || 'build';
process.env.DEPLOY_PROFILE = process.env.DEPLOY_PROFILE || 'alpha-dev-sveltekitphp';

function fail(message) {
	console.error(message);
	process.exit(1);
}

function normalizeRemotePath(raw) {
	return String(raw || '')
		.trim()
		.replace(/\\/g, '/')
		.replace(/\/+$/, '');
}

function assertDevRemotePath(remotePath) {
	const normalized = normalizeRemotePath(remotePath);
	const expectedSuffix = devBasePath.replace(/^\//, '');

	if (!normalized) {
		fail('DEPLOY_REMOTE is required and must point at the isolated alpha dev directory.');
	}

	if (!new RegExp(`(^|/)${expectedSuffix.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}$`).test(normalized)) {
		fail(`DEPLOY_REMOTE must end with ${devBasePath} for the alpha dev-host lane.`);
	}

	if (/^(\/?|\.|~|public_html|domains\/[^/]+\/public_html)$/i.test(normalized)) {
		fail(`Refusing broad DEPLOY_REMOTE for alpha dev-host lane: ${normalized}`);
	}
}

function assertSmokeBasePath(raw) {
	const url = new URL(String(raw || ''));
	const normalizedPath = normalizeBase(url.pathname);

	if (normalizedPath !== devBasePath) {
		fail(`ALPHA_SMOKE_BASE_URL must target ${devBasePath} for the alpha dev-host lane.`);
	}
}

function stripLeadingSlash(value) {
	return String(value || '').replace(/^\/+/, '');
}

async function writeIsolatedDevHostHtaccess() {
	const baseRel = stripLeadingSlash(devBasePath);
	const buildRoot = path.join(repoRoot, 'build');
	const nestedAppRoot = path.join(buildRoot, ...baseRel.split('/'));

	try {
		await writeFile(
			path.join(buildRoot, '.htaccess'),
			`# Apache configuration for isolated SvelteKit PHP alpha dev-host proof
# Generated by scripts/deploy-alpha-dev-host.mjs
#
# This file is intentionally different from the document-root adapter .htaccess.
# The live proof uploads build/ into /dev/sveltekitphp, while SvelteKit's base
# path output places PHP pages under build/${baseRel}. Static assets/runtime stay
# at the upload root.

<IfModule mod_rewrite.c>
	RewriteEngine On
	Options -MultiViews
	DirectoryIndex index.php index.html

	# deny dotfiles and protected runtime internals
	RewriteRule (^|/)\\. - [F,L]
	RewriteRule ^(?:${baseRel}/)?(?:_protected|_runtime|adapter)/ - [F,L]

	# let immutable assets and existing files through
	RewriteRule ^_app/ - [L]
	RewriteCond %{REQUEST_FILENAME} -f
	RewriteRule ^ - [L]

	# app-root requests route to the nested base-path PHP entrypoint
	RewriteRule ^(?:index\\.php)?$ ${baseRel}/index.php [QSA,L]

	# SvelteKit data/action requests map to generated PHP bridge files
	RewriteCond %{DOCUMENT_ROOT}/${baseRel}/$1__data.php -f
	RewriteRule ^(.*/)?__data\\.json$ $1__data.php [QSA,END]
	RewriteCond %{DOCUMENT_ROOT}/${baseRel}/$1__action.php -f
	RewriteRule ^(.*/)?__action$ $1__action.php [QSA,END]

	# Extension-named endpoints can be generated as directories, e.g. route.json/index.php
	RewriteCond %{DOCUMENT_ROOT}/${baseRel}/$1/index.php -f
	RewriteRule ^(.+\\.[A-Za-z0-9]+?)/?$ $1/index.php [QSA,END]

	# Directory-style page routes map to nested generated index.php files
	RewriteCond %{DOCUMENT_ROOT}/${baseRel}/${baseRel}/$1/index.php -f
	RewriteRule ^(.+?)/?$ ${baseRel}/$1/index.php [QSA,L]

	# Extensionless PHP routes/endpoints map to nested generated PHP files
	RewriteCond %{DOCUMENT_ROOT}/${baseRel}/${baseRel}/$1.php -f
	RewriteRule ^(.+?)/?$ ${baseRel}/$1.php [QSA,L]

	# Final fallback to the generated PHP router at the upload root
	RewriteRule ^.*$ router.php [QSA,L]
</IfModule>

<IfModule mod_headers.c>
	Header always set X-Content-Type-Options "nosniff"
	<IfModule mod_setenvif.c>
		SetEnvIf Request_URI "^${devBasePath}/_app/" SK_ASSET=1
		SetEnvIf Request_URI "__data\\.json$" SK_DATA=1
		SetEnvIf Request_URI "__action$" SK_ACTION=1
	</IfModule>
	Header set Cache-Control "public, max-age=31536000, immutable" env=SK_ASSET
	Header set Cache-Control "no-store" env=SK_DATA
	Header set Cache-Control "no-store" env=SK_ACTION
</IfModule>

<IfModule mod_mime.c>
	AddType text/markdown       .md
	AddType text/csv            .csv
	AddType image/svg+xml       .svg
	AddType application/json    .json
</IfModule>
`,
			'utf8'
		);
	} catch (error) {
		fail(`Failed to write isolated alpha dev-host .htaccess: ${error.message}`);
	}

	try {
		await writeFile(
			path.join(buildRoot, 'index.php'),
			`<?php
// Isolated alpha dev-host DirectoryIndex shim.
// The generated base-path app lives under ${baseRel}/ inside this upload root.
require __DIR__ . '/${baseRel}/index.php';
`,
			'utf8'
		);
	} catch (error) {
		fail(`Failed to write isolated alpha dev-host index.php shim: ${error.message}`);
	}

	console.log(`Prepared isolated alpha dev-host Apache routing for ${devBasePath}.`);
	console.log(`Nested generated app root: ${nestedAppRoot}`);
}

function runStep(name, command, stepArgs, env = process.env) {
	return new Promise((resolve, reject) => {
		console.log(`\n==> ${name}`);
		console.log(`$ ${command} ${stepArgs.join(' ')}`);

		const child = spawn(command, stepArgs, {
			cwd: repoRoot,
			env,
			stdio: 'inherit',
			shell: process.platform === 'win32'
		});

		child.on('error', reject);
		child.on('close', (code) => {
			if (code === 0) {
				resolve();
				return;
			}
			reject(new Error(`${name} failed with exit code ${code}`));
		});
	});
}

async function main() {
	if (devBasePath !== '/dev/sveltekitphp') {
		fail('ALPHA_DEV_BASE_PATH is intentionally pinned to /dev/sveltekitphp for this proof lane.');
	}

	if (!skipBuild) {
		await runStep('Build adapter bundle', 'bun', ['run', 'build:adapter']);
		await runStep('Build Apache/PHP output for /dev/sveltekitphp', 'bun', ['run', 'build:apache']);
	}

	await writeIsolatedDevHostHtaccess();

	if (buildOnly) {
		console.log('\nAlpha dev-host build completed without upload.');
		return;
	}

	assertDeployEnv('Alpha dev-host deploy');
	assertDevRemotePath(process.env.DEPLOY_REMOTE);

	if (!apply) {
		console.log('\nAlpha dev-host deploy precheck passed.');
		console.log('No upload performed. Re-run with --apply to upload to the guarded /dev/sveltekitphp target.');
		return;
	}

	await runStep('Upload build to guarded alpha dev-host directory', 'bun', [
		'tools/deploy-build.ts',
		'--archive',
		'--cleanup-wait',
		'--yes'
	]);

	if (smoke) {
		assertHostedSmokeEnv('Alpha dev-host smoke');
		assertSmokeBasePath(process.env.ALPHA_SMOKE_BASE_URL);
		await runStep('Run hosted alpha smoke against /dev/sveltekitphp', 'bun', ['run', 'alpha:remote:smoke']);
		await runStep('Regenerate alpha report with hosted evidence', 'bun', ['run', 'alpha:report']);
		await runStep('Verify alpha report with hosted evidence', 'bun', ['run', 'verify:alpha']);
	}
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
	await main();
}
